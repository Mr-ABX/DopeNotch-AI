// clipboard_listener.rs - Native background system clipboard monitor and persistence
use std::sync::{Arc, Mutex};
use tauri::{AppHandle, Emitter};
use tauri_plugin_clipboard_manager::ClipboardExt;
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ClipboardItemPayload {
    pub id: String,
    pub content: String,
    pub category: String,
    pub timestamp: String,
    pub timestamp_raw: i64,
    pub source_app: String,
    pub char_count: usize,
    pub word_count: usize,
    pub is_pinned: bool,
}

#[cfg(target_os = "macos")]
pub fn get_frontmost_app_name() -> String {
    use objc2::msg_send;
    use objc2::runtime::AnyObject;
    use std::ffi::CStr;

    unsafe {
        let ws_cls = objc2::ffi::objc_getClass(b"NSWorkspace\0".as_ptr() as *const _);
        if ws_cls.is_null() {
            return "Clipboard".to_string();
        }
        let ws: *mut AnyObject = msg_send![ws_cls as *mut AnyObject, sharedWorkspace];
        if ws.is_null() {
            return "Clipboard".to_string();
        }
        let front_app: *mut AnyObject = msg_send![ws, frontmostApplication];
        if front_app.is_null() {
            return "Clipboard".to_string();
        }
        let name_ns: *mut AnyObject = msg_send![front_app, localizedName];
        if name_ns.is_null() {
            return "Clipboard".to_string();
        }
        let utf8: *const std::os::raw::c_char = msg_send![name_ns, UTF8String];
        if !utf8.is_null() {
            if let Ok(s) = CStr::from_ptr(utf8).to_str() {
                return s.to_string();
            }
        }
    }
    "Clipboard".to_string()
}

#[cfg(not(target_os = "macos"))]
pub fn get_frontmost_app_name() -> String {
    "Clipboard".to_string()
}

#[cfg(target_os = "macos")]
pub fn is_macos_pasteboard_sensitive() -> bool {
    use objc2::msg_send;
    use objc2::runtime::AnyObject;
    use std::ffi::CStr;

    unsafe {
        let pb_cls = objc2::ffi::objc_getClass(b"NSPasteboard\0".as_ptr() as *const _);
        if pb_cls.is_null() {
            return false;
        }
        let general_pb: *mut AnyObject = msg_send![pb_cls as *mut AnyObject, generalPasteboard];
        if general_pb.is_null() {
            return false;
        }

        // Retrieve the registered pasteboard types for the current copied payload
        let types: *mut AnyObject = msg_send![general_pb, types];
        if types.is_null() {
            return false;
        }

        let count: usize = msg_send![types, count];
        for i in 0..count {
            let item_type: *mut AnyObject = msg_send![types, objectAtIndex: i];
            if !item_type.is_null() {
                let utf8: *const std::os::raw::c_char = msg_send![item_type, UTF8String];
                if !utf8.is_null() {
                    if let Ok(type_str) = CStr::from_ptr(utf8).to_str() {
                        let lower = type_str.to_lowercase();
                        // Apple standard concealed/transient types & Password managers
                        if lower.contains("concealedtype")
                            || lower.contains("transienttype")
                            || lower.contains("autogeneratedtype")
                            || lower.contains("onepassword")
                            || lower.contains("bitwarden")
                            || lower.contains("keepass")
                            || lower.contains("dashlane")
                            || lower.contains("xkey.password")
                        {
                            return true;
                        }
                    }
                }
            }
        }
    }
    false
}

#[cfg(not(target_os = "macos"))]
pub fn is_macos_pasteboard_sensitive() -> bool {
    false
}

#[cfg(target_os = "macos")]
pub fn get_macos_pasteboard_text() -> Option<String> {
    use objc2::msg_send;
    use objc2::runtime::AnyObject;
    use std::ffi::CStr;

    unsafe {
        let pb_cls = objc2::ffi::objc_getClass(b"NSPasteboard\0".as_ptr() as *const _);
        if pb_cls.is_null() {
            return None;
        }
        let general_pb: *mut AnyObject = msg_send![pb_cls as *mut AnyObject, generalPasteboard];
        if general_pb.is_null() {
            return None;
        }

        let str_cls = objc2::ffi::objc_getClass(b"NSString\0".as_ptr() as *const _);
        
        // 1. Try public.utf8-plain-text
        let ns_type_str: *mut AnyObject = msg_send![str_cls as *mut AnyObject, stringWithUTF8String: b"public.utf8-plain-text\0".as_ptr()];
        let item_ns: *mut AnyObject = msg_send![general_pb, stringForType: ns_type_str];
        if !item_ns.is_null() {
            let utf8: *const std::os::raw::c_char = msg_send![item_ns, UTF8String];
            if !utf8.is_null() {
                if let Ok(s) = CStr::from_ptr(utf8).to_str() {
                    return Some(s.to_string());
                }
            }
        }

        // 2. Try NSStringPboardType
        let legacy_type: *mut AnyObject = msg_send![str_cls as *mut AnyObject, stringWithUTF8String: b"NSStringPboardType\0".as_ptr()];
        let item_ns2: *mut AnyObject = msg_send![general_pb, stringForType: legacy_type];
        if !item_ns2.is_null() {
            let utf8: *const std::os::raw::c_char = msg_send![item_ns2, UTF8String];
            if !utf8.is_null() {
                if let Ok(s) = CStr::from_ptr(utf8).to_str() {
                    return Some(s.to_string());
                }
            }
        }
    }
    None
}

/// Detect item category based on text patterns
pub fn detect_category(text: &str) -> String {
    let trimmed = text.trim();
    
    // 1. Color check (Hex #RGB, #RRGGBB, #RRGGBBAA or rgb(...))
    if (trimmed.starts_with('#') && (trimmed.len() == 4 || trimmed.len() == 7 || trimmed.len() == 9) && trimmed[1..].chars().all(|c| c.is_ascii_hexdigit()))
        || (trimmed.starts_with("rgb(") && trimmed.ends_with(')'))
        || (trimmed.starts_with("rgba(") && trimmed.ends_with(')')) {
        return "color".to_string();
    }

    // 2. Link check
    if trimmed.starts_with("http://") || trimmed.starts_with("https://") {
        return "link".to_string();
    }

    // 3. Code check
    if (trimmed.contains("const ") || trimmed.contains("let ") || trimmed.contains("var ")
        || trimmed.contains("function ") || trimmed.contains("def ") || trimmed.contains("import ")
        || trimmed.contains("class ") || trimmed.contains("fn ") || trimmed.contains("pub ")
        || trimmed.contains("return ") || trimmed.contains("=>") || trimmed.contains("console.log")
        || (trimmed.contains('{') && trimmed.contains('}'))
        || (trimmed.contains('<') && trimmed.contains('>'))
        || trimmed.starts_with("git ") || trimmed.starts_with("npm ") || trimmed.starts_with("cargo "))
        && (trimmed.contains('\n') || trimmed.len() > 15) {
        return "code".to_string();
    }

    "clipboard".to_string()
}

/// Path to persistent clipboard storage JSON (~/Documents/DopeNotch/history/clipboard_history.json)
fn clipboard_storage_path() -> std::path::PathBuf {
    let settings = crate::settings::AppSettings::load_or_default();
    let root = crate::storage::DopeNotchStorage::get_root(settings.storage_directory.as_deref());
    let target = crate::storage::DopeNotchStorage::clipboard_file(&root);

    if !target.exists() {
        let base = dirs::data_dir().unwrap_or_else(|| std::path::PathBuf::from("."));
        let murmur_clip = base.join("Murmur").join("clipboard_history.json");
        if murmur_clip.exists() {
            if let Some(parent) = target.parent() {
                let _ = std::fs::create_dir_all(parent);
            }
            let _ = std::fs::copy(&murmur_clip, &target);
            return target;
        }
        let dopenotch_clip = base.join("DopeNotch").join("clipboard_history.json");
        if dopenotch_clip.exists() {
            if let Some(parent) = target.parent() {
                let _ = std::fs::create_dir_all(parent);
            }
            let _ = std::fs::copy(&dopenotch_clip, &target);
            return target;
        }
    }

    if let Some(parent) = target.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    target
}

pub fn load_saved_clipboard() -> Vec<ClipboardItemPayload> {
    let path = clipboard_storage_path();
    if path.exists() {
        if let Ok(data) = std::fs::read_to_string(&path) {
            if let Ok(items) = serde_json::from_str::<Vec<ClipboardItemPayload>>(&data) {
                return items;
            }
        }
    }
    Vec::new()
}

pub fn save_clipboard_to_disk(items: &[ClipboardItemPayload]) {
    let path = clipboard_storage_path();
    if let Ok(json) = serde_json::to_string_pretty(items) {
        let _ = std::fs::write(path, json);
    }
}

#[cfg(target_os = "macos")]
extern "C" {
    fn get_system_pasteboard_change_count() -> std::os::raw::c_long;
    fn get_pasteboard_image_as_base64() -> *mut std::os::raw::c_char;
    fn free_c_string(s: *mut std::os::raw::c_char);
}

#[cfg(target_os = "macos")]
pub fn get_macos_pasteboard_image() -> Option<String> {
    unsafe {
        let ptr = get_pasteboard_image_as_base64();
        if ptr.is_null() {
            return None;
        }
        let c_str = std::ffi::CStr::from_ptr(ptr);
        let res = c_str.to_str().ok().map(|s| s.to_string());
        free_c_string(ptr);
        res
    }
}

/// Starts background thread to monitor OS clipboard changes live
pub fn start_clipboard_monitor(app_handle: AppHandle) {
    tauri::async_runtime::spawn(async move {
        let last_change_count = Arc::new(Mutex::new(0i64));
        let last_content = Arc::new(Mutex::new(String::new()));
        
        // Prime last values with current clipboard so app start doesn't trigger spurious change
        #[cfg(target_os = "macos")]
        {
            let count = unsafe { get_system_pasteboard_change_count() };
            *last_change_count.lock().unwrap() = count as i64;
            if let Some(initial_img) = get_macos_pasteboard_image() {
                *last_content.lock().unwrap() = initial_img;
            } else if let Some(initial_text) = get_macos_pasteboard_text() {
                *last_content.lock().unwrap() = initial_text;
            }
        }

        #[cfg(not(target_os = "macos"))]
        if let Ok(initial_text) = app_handle.clipboard().read_text() {
            *last_content.lock().unwrap() = initial_text;
        }

        loop {
            tokio::time::sleep(tokio::time::Duration::from_millis(200)).await;

            #[cfg(target_os = "macos")]
            {
                let count = unsafe { get_system_pasteboard_change_count() } as i64;
                let mut last_cc = last_change_count.lock().unwrap();
                if count == *last_cc {
                    continue;
                }
                *last_cc = count;
                drop(last_cc);

                // Security & Privacy Gate: Skip capturing concealed/transient passwords
                if is_macos_pasteboard_sensitive() {
                    log::debug!("[clipboard] Skipping sensitive password manager pasteboard item");
                    continue;
                }
            }

            // 1. Check if an image was copied to pasteboard
            let image_opt = {
                #[cfg(target_os = "macos")]
                {
                    get_macos_pasteboard_image()
                }
                #[cfg(not(target_os = "macos"))]
                {
                    None::<String>
                }
            };

            if let Some(img_data) = image_opt {
                let mut last = last_content.lock().unwrap();
                if *last != img_data {
                    *last = img_data.clone();
                    drop(last);

                    let source_app = get_frontmost_app_name();
                    let now = chrono::Utc::now().timestamp_millis();

                    let item = ClipboardItemPayload {
                        id: format!("clip-{}", now),
                        content: img_data,
                        category: "image".to_string(),
                        timestamp: "Just now".to_string(),
                        timestamp_raw: now,
                        source_app,
                        char_count: 0,
                        word_count: 0,
                        is_pinned: false,
                    };

                    let mut saved = load_saved_clipboard();
                    saved.retain(|c| c.content != item.content);
                    saved.insert(0, item.clone());
                    let max_clips = if crate::license::is_pro_active() { 1000 } else { 25 };
                    if saved.len() > max_clips {
                        saved.truncate(max_clips);
                    }
                    save_clipboard_to_disk(&saved);

                    log::info!("[clipboard] Captured new image from {}", item.source_app);

                    let _ = app_handle.emit("murmur://clipboard-changed", &item);
                    let _ = app_handle.emit("murmur://clipboard-history-updated", &saved);
                    continue;
                }
            }

            // 2. Check if text was copied to pasteboard
            let current_text_opt = {
                #[cfg(target_os = "macos")]
                {
                    get_macos_pasteboard_text().or_else(|| app_handle.clipboard().read_text().ok())
                }
                #[cfg(not(target_os = "macos"))]
                {
                    app_handle.clipboard().read_text().ok()
                }
            };

            if let Some(current_text) = current_text_opt {
                let trimmed = current_text.trim();
                if trimmed.is_empty() {
                    continue;
                }

                let mut last = last_content.lock().unwrap();
                if *last != trimmed {
                    *last = trimmed.to_string();
                    drop(last);

                    let source_app = get_frontmost_app_name();
                    let category = detect_category(trimmed);
                    let now = chrono::Utc::now().timestamp_millis();
                    let char_count = trimmed.chars().count();
                    let word_count = trimmed.split_whitespace().count();

                    let item = ClipboardItemPayload {
                        id: format!("clip-{}", now),
                        content: trimmed.to_string(),
                        category,
                        timestamp: "Just now".to_string(),
                        timestamp_raw: now,
                        source_app,
                        char_count,
                        word_count,
                        is_pinned: false,
                    };

                    // Persist to disk
                    let mut saved = load_saved_clipboard();
                    // Remove duplicate content so latest copy bubbles to the front
                    saved.retain(|c| c.content != item.content);
                    saved.insert(0, item.clone());
                    let max_clips = if crate::license::is_pro_active() { 1000 } else { 25 };
                    if saved.len() > max_clips {
                        saved.truncate(max_clips);
                    }
                    save_clipboard_to_disk(&saved);

                    log::info!("[clipboard] Captured new item: {} chars from {}", char_count, item.source_app);

                    // Broadcast live update to all windows
                    let _ = app_handle.emit("murmur://clipboard-changed", &item);
                    let _ = app_handle.emit("murmur://clipboard-history-updated", &saved);
                }
            }
        }
    });
}
